"""Fullscreen pygame launcher for other pygame programs.

Navigation: joystick / arcade controls (or keyboard equivalents).
Exit: keyboard only (Escape, Alt+F4 / window close).
"""

import configparser
import os
import subprocess
import sys

import pygame

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
CONFIG_FILE = os.path.join(BASE_DIR, "config.ini")

BG_COLOR = (255, 255, 255)
TEXT_COLOR = (0, 0, 0)
MARGIN = 40

AXIS_THRESHOLD = 0.5
REPEAT_DELAY = 0.35   # seconds before a held direction starts repeating
REPEAT_INTERVAL = 0.1  # seconds between repeats while held
ERROR_TAIL_LINES = 15

# Keyboard equivalents: arrows for player 1, W/S for player 2.
KEYS_UP = {pygame.K_UP, pygame.K_w}
KEYS_DOWN = {pygame.K_DOWN, pygame.K_s}
KEYS_SELECT = {pygame.K_RETURN, pygame.K_KP_ENTER, pygame.K_SPACE,
               pygame.K_LCTRL, pygame.K_LALT}

UP, DOWN, SELECT = "up", "down", "select"


def load_config():
    cfg = configparser.ConfigParser()
    cfg.read(CONFIG_FILE)
    sec = cfg["launcher"] if cfg.has_section("launcher") else {}
    script_dir = sec.get("script_dir", "games")
    if not os.path.isabs(script_dir):
        script_dir = os.path.join(BASE_DIR, script_dir)
    return {
        "script_dir": os.path.normpath(script_dir),
        "python": sec.get("python", "") or sys.executable,
        "font_size": int(sec.get("font_size", 16)),
    }


def find_programs(script_dir):
    """Return a sorted list of (name, script_path).

    A program is either a top-level ``*.py`` file or a sub-directory that
    contains a ``main.py`` (for games that ship with their own assets).
    """
    programs = []
    if not os.path.isdir(script_dir):
        return programs
    for entry in os.listdir(script_dir):
        path = os.path.join(script_dir, entry)
        if os.path.isfile(path) and entry.endswith(".py"):
            programs.append((entry[:-3], path))
        elif os.path.isdir(path) and os.path.isfile(os.path.join(path, "main.py")):
            programs.append((entry, os.path.join(path, "main.py")))
    programs.sort(key=lambda p: p[0].lower())
    return programs


def run_program(python, script):
    """Run a script to completion. Returns (exit_code, error_text or None)."""
    try:
        proc = subprocess.run([python, script], cwd=os.path.dirname(script),
                              stderr=subprocess.PIPE)
    except OSError as exc:
        return None, f"Could not start program: {exc}"
    stderr = proc.stderr.decode(errors="replace")
    if stderr:
        sys.stderr.write(stderr)  # keep it visible in the console/journal too
    if proc.returncode == 0:
        return 0, None
    lines = stderr.strip().splitlines()[-ERROR_TAIL_LINES:]
    if proc.returncode < 0 and not lines:
        lines = [f"Terminated by signal {-proc.returncode}"]
    return proc.returncode, "\n".join(lines) or "(no error output)"


class Input:
    """Turns keyboard / joystick events into UP, DOWN, SELECT actions,
    with auto-repeat for held directions. Any connected joystick works,
    so both players' controls can drive the menu."""

    def __init__(self):
        self.joysticks = {}
        self.held = {}  # source -> [direction, time_until_next_repeat]

    def open_joysticks(self):
        self.joysticks.clear()
        self.held.clear()
        for i in range(pygame.joystick.get_count()):
            js = pygame.joystick.Joystick(i)
            self.joysticks[js.get_instance_id()] = js

    def _press(self, source, direction, actions):
        if direction is None:
            self.held.pop(source, None)
        elif self.held.get(source, [None])[0] != direction:
            self.held[source] = [direction, REPEAT_DELAY]
            actions.append(direction)

    def handle(self, event):
        """Return a list of actions generated by this event."""
        actions = []
        t = event.type
        if t == pygame.JOYDEVICEADDED:
            js = pygame.joystick.Joystick(event.device_index)
            self.joysticks[js.get_instance_id()] = js
        elif t == pygame.JOYDEVICEREMOVED:
            self.joysticks.pop(event.instance_id, None)
            for src in [s for s in self.held if s[0] == event.instance_id]:
                del self.held[src]
        elif t == pygame.KEYDOWN:
            if event.key in KEYS_UP:
                self._press(("key", event.key), UP, actions)
            elif event.key in KEYS_DOWN:
                self._press(("key", event.key), DOWN, actions)
            elif event.key in KEYS_SELECT:
                actions.append(SELECT)
        elif t == pygame.KEYUP:
            self.held.pop(("key", event.key), None)
        elif t == pygame.JOYBUTTONDOWN:
            actions.append(SELECT)
        elif t == pygame.JOYHATMOTION:
            y = event.value[1]
            self._press((event.instance_id, "hat", event.hat),
                        UP if y > 0 else DOWN if y < 0 else None, actions)
        elif t == pygame.JOYAXISMOTION and event.axis % 2 == 1:
            v = event.value
            self._press((event.instance_id, "axis", event.axis),
                        UP if v < -AXIS_THRESHOLD else
                        DOWN if v > AXIS_THRESHOLD else None, actions)
        return actions

    def update(self, dt):
        """Return repeat actions for held directions."""
        actions = []
        for state in self.held.values():
            state[1] -= dt
            if state[1] <= 0:
                state[1] += REPEAT_INTERVAL
                actions.append(state[0])
        return actions


def is_quit(event):
    if event.type == pygame.QUIT:
        return True
    if event.type == pygame.KEYDOWN:
        if event.key == pygame.K_ESCAPE:
            return True
        if event.key == pygame.K_F4 and event.mod & pygame.KMOD_ALT:
            return True
    return False


class Launcher:
    def __init__(self, config):
        self.config = config
        self.programs = find_programs(config["script_dir"])
        self.selected = 0
        self.result = None  # (name, exit_code, error_text) after a failed run
        self.input = Input()
        self.font = None
        self.screen = None

    # -- display lifecycle -------------------------------------------------

    def open_display(self):
        pygame.display.init()
        pygame.joystick.init()
        pygame.font.init()
        self.screen = pygame.display.set_mode((0, 0), pygame.FULLSCREEN)
        pygame.display.set_caption("Launcher")
        pygame.mouse.set_visible(False)
        self.font = pygame.font.Font(None, self.config["font_size"])
        self.input.open_joysticks()
        pygame.event.clear()

    def close_display(self):
        """Release the screen and controllers so the child program gets them."""
        self.input.joysticks.clear()
        pygame.joystick.quit()
        pygame.display.quit()

    # -- actions -----------------------------------------------------------

    def launch(self):
        if not self.programs:
            return
        name, script = self.programs[self.selected]
        self.close_display()
        code, error = run_program(self.config["python"], script)
        self.open_display()
        self.programs = find_programs(self.config["script_dir"])
        self.selected = min(self.selected, max(len(self.programs) - 1, 0))
        if error is not None:
            self.result = (name, code, error)

    def act(self, action):
        if self.result is not None:
            # Error screen: any control press dismisses it.
            self.result = None
            return
        if action == UP:
            self.selected = max(self.selected - 1, 0)
        elif action == DOWN:
            self.selected = min(self.selected + 1, len(self.programs) - 1)
        elif action == SELECT:
            self.launch()

    # -- drawing -----------------------------------------------------------

    def text_lines(self):
        if self.result is not None:
            name, code, error = self.result
            lines = [f"'{name}' exited with code {code}", ""]
            lines += error.splitlines()
            lines += ["", "Press any button to continue"]
            return lines
        if not self.programs:
            return [f"No programs found in {self.config['script_dir']}"]
        line_h = self.font.get_linesize()
        visible = max((self.screen.get_height() - 2 * MARGIN) // line_h, 1)
        first = min(max(self.selected - visible // 2, 0),
                    max(len(self.programs) - visible, 0))
        return [("> " if i == self.selected else "   ") + name
                for i, (name, _) in enumerate(self.programs)][first:first + visible]

    def draw(self):
        self.screen.fill(BG_COLOR)
        y = MARGIN
        for line in self.text_lines():
            self.screen.blit(self.font.render(line, True, TEXT_COLOR), (MARGIN, y))
            y += self.font.get_linesize()
        pygame.display.flip()

    # -- main loop ---------------------------------------------------------

    def run(self):
        self.open_display()
        clock = pygame.time.Clock()
        while True:
            dt = clock.tick(60) / 1000
            actions = []
            for event in pygame.event.get():
                if is_quit(event):
                    return
                actions += self.input.handle(event)
            actions += self.input.update(dt)
            for action in actions:
                self.act(action)
                if action == SELECT:
                    break  # discard anything queued from before a launch
            self.draw()


def main():
    try:
        Launcher(load_config()).run()
    finally:
        pygame.quit()


if __name__ == "__main__":
    main()
